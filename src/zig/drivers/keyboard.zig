// Keyboard Drivers

// Extern Functions 
extern fn driver_keyboard_get_code() u8;

// Functions 
// Get code from Keyboard
pub fn get_code() u8 {
  return driver_keyboard_get_code();
}



// Export functions
// Keyboard Layout for byte entry (One number)
export fn keyboard_layout_byte(int: u8) [2]u8 {
  // Keyboard Code => .{ASCII Code, Released?}
  return switch (int) {
    // 1
    0x02 => .{0x31, 0},
    0x82 => .{0x31, 1},
    // 2
    0x03 => .{0x32, 0},
    0x83 => .{0x32, 1},
    // 3
    0x04 => .{0x33, 0},
