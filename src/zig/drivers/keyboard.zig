    0xAC => .{0x7A, 1},
    // x
    0x2D => .{0x78, 0},
    0xAD => .{0x78, 1},
    // c
    0x2E => .{0x63, 0},
    0xAE => .{0x63, 1},
    // v
    0x2F => .{0x76, 0},
    0xAF => .{0x76, 1},
    // b
    0x30 => .{0x62, 0},
    0xB0 => .{0x62, 1},
    // n
