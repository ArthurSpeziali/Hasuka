    0xBD => .{0xE7, 1},
    // F4
    0x3E => .{0xE7, 0},
    0xBE => .{0x00, 1},
    // F5
    0x3F => .{0xE7, 0},
    0xBF => .{0xE7, 1},
    // F6
    0x40 => .{0xE7, 0},
    0xC0 => .{0xE7, 1},
    // F7
    0x41 => .{0xE7, 0},
    0xC1 => .{0xE7, 1},
    // F8
    0x42 => .{0xE7, 0},
    0xC2 => .{0xE7, 1},
    // 
    else => .{0x00, 0},
  };
}

