    0x89 => .{0x38, 1},
    // 9
    0x0A => .{0x39, 0},
    0x8A => .{0x39, 1},
    // 0
    0x0B => .{0x30, 0},
    0x8B => .{0x30, 1},
    // -
    0x0C => .{0x2D, 0},
    0x8C => .{0x2D, 1},
    // +
    0x0D => .{0x2B, 0},
    0x8D => .{0x2B, 1},
    // "
    0x29 => .{0x22, 0},
    0xA9 => .{0x22, 1},
    // q
    0x10 => .{0x71, 0},
    0x90 => .{0x71, 1},
