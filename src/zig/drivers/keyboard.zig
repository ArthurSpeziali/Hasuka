    // s
    0x1F => .{0x73, 0},
    0x9F => .{0x73, 1},
    // d
    0x20 => .{0x64, 0},
    0xA0 => .{0x64, 1},
    // f
    0x21 => .{0x66, 0},
    0xA1 => .{0x66, 1},
